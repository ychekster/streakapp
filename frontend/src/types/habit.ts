/** Типы данных привычек — зеркалят схемы ответа API (backend/schemas.py). */

import type { HABIT_COLORS } from "../constants";

/** Цвет палитры — ключ `--palette-*`. */
export type PaletteColor = (typeof HABIT_COLORS)[number];

/** Цвет (тема) привычки — ключ палитры или свой цвет «#rrggbb» (палитра в форме). */
export type HabitColor = PaletteColor | `#${string}`;

export interface Habit {
  /** Идентификатор задачи. */
  id: number;
  /** Название привычки. */
  name: string;
  /** Описание (серым под названием); null — без описания. Нет у привычек, сохранённых
   *  на устройстве до описаний. */
  description?: string | null;
  /** Отмечена ли задача выполненной сегодня. */
  done_today: boolean;
  /**
   * Запланирована ли задача на сегодня. false — отметить всё равно можно, но отметка
   * бонусная: в сетке, календаре и «всего» есть, в сериях и счёте периода — нет.
   */
  scheduled_today: boolean;
  /** Частота: каждый день, конкретные дни недели или через день. */
  frequency_type: FrequencyType;
  /** Коды дней недели (mon..sun) для specific_days; для остальных — пустой массив. */
  days: string[];
  /** Первый день привычки every_other_day («ГГГГ-ММ-ДД»), дальше — каждый второй, или
   *  monthly — дальше то же число каждого месяца; иначе null. */
  start_date: string | null;
  /** «Гибкий график» (flexible): календарный период (неделя с понедельника, месяц с 1-го,
   *  год с 1 января); иначе null. Нет у привычек, сохранённых до «Гибкого графика». */
  period?: Period | null;
  /** «Гибкий график»: сколько дней за период (в коротком — не больше его дней). */
  period_times?: number | null;
  /** «Гибкий график»: сколько дней выполнено в текущем периоде (в совместной — мной). */
  period_done?: number;
  /** «Гибкий график»: серия (в периодах) по закончившимся периодам — без текущего;
   *  набрана цель текущего — на 1 больше (data/derive.ts). */
  prior_streak?: number;
  /** «Гибкий график»: лучшая серия по закончившимся периодам. */
  prior_best?: number;
  /**
   * Выполнение за последние HISTORY_DAYS дней (старое → сегодня).
   * true — день выполнен, false — пропущен/нет данных.
   * Индекс 0 — самый старый день, последний элемент — сегодня.
   */
  history: boolean[];
  /**
   * Текущая серия: подряд выполненные дни по сегодня включительно. Неотмеченный
   * сегодняшний день серию не прерывает — день ещё не закончился.
   */
  current_streak: number;
  /** Лучшая серия за всё время. */
  best_streak: number;
  /** Сколько раз привычка выполнена за всё время (и бонусные отметки). */
  total_done: number;
  /** Первое (самое раннее) напоминание «ЧЧ:ММ» в поясе пользователя; null — без
   *  напоминания. */
  reminder_time: string | null;
  /** Все напоминания «ЧЧ:ММ» по возрастанию; пустой — без напоминания. У привычек,
   *  сохранённых на устройстве до нескольких напоминаний, нет — см. reminderTimesOf. */
  reminder_times: string[];
  /** Цвет (тема) привычки. */
  color: HabitColor;
  /**
   * С какого дня («ГГГГ-ММ-ДД») привычка заморожена; null — не заморожена. Замороженную
   * нельзя отмечать, пропуски не прерывают её серию, напоминания не приходят.
   */
  frozen_since: string | null;
  /** В архиве: привычка работает как обычная, но её нет в списке привычек и папках — она
   *  в «Архиве» настроек; напоминания не приходят. Нет — сохранена до архива (не в нём). */
  archived?: boolean;
  /** Дни заморозки за те же дни, что `history` (текущая заморозка и прошедшие). */
  frozen_history: boolean[];
  /** Сколько раз в день нужно выполнить привычку (1 — обычная привычка); у «Цели по
   *  времени» — сколько секунд. */
  times_per_day: number;
  /** «Цель по времени»: seconds — цель и счёт дня (`today_count`, `history_counts`) в
   *  секундах, время копит таймер; times (или нет — сохранена до таймера) — в разах. */
  goal_unit?: GoalUnit;
  /** Сколько раз привычка выполнена в день отметки; день выполнен, когда набрано
   *  `times_per_day`. */
  today_count: number;
  /** Сколько раз привычка выполнена в каждый день `history` — у привычек «несколько раз
   *  в день» (у остальных пустой): неполный день сетка закрашивает долей цвета. Нет у
   *  привычек, сохранённых на устройстве до этого поля. */
  history_counts?: number[];
  /** Выполнен ли день после дня отметки — в режиме «Отмечать за вчера» это календарный
   *  сегодня (иначе false): выключили режим — сегодняшние отметки видны сразу. */
  next_day_done?: boolean;
  /** Сколько раз выполнена в тот же день (привычка «несколько раз в день»; у совместной —
   *  моя часть при любой цели, выполненный день — цель). */
  next_day_count?: number;
  /** День создания («ГГГГ-ММ-ДД», в поясе пользователя): с него сетка «Вида сетки» fixed
   *  начинается с левого верхнего кружка. Нет у привычек, сохранённых на устройстве до
   *  этого поля. */
  created_on?: string | null;
  /** Первый день привычки («ГГГГ-ММ-ДД», может быть старше `history`): первая отметка
   *  или первый день заморозки — что раньше; null — ни того ни другого. С него
   *  начинается сетка fixed. Нет у привычек, сохранённых на устройстве до этого поля. */
  started_on?: string | null;
  /** «Автоотметка»: без напоминания — выполнена с началом дня, с напоминаниями —
   *  сразу после последнего (отмечает бот). Только у привычек «раз в день». */
  auto_mark: boolean;
  /** «Сверх плана»: счёт идёт вверх и не останавливается на цели (до OVERTIME_MAX_COUNT),
   *  долгое нажатие убирает один раз. Только у привычек «несколько раз в день». Нет у
   *  привычек, сохранённых на устройстве до этого поля. */
  overtime?: boolean;
  /** За календарный сегодня (в режиме «Отмечать за вчера» — день после дня отметки)
   *  записи ещё нет — ни отметки, ни снятой: автоотметку за него приложение покажет само,
   *  когда ей пора (data/derive.ts). Нет у привычек, сохранённых до этого поля. */
  auto_mark_ahead?: boolean;
  /** Прежние расписания по возрастанию `until`: прошлые дни оцениваются по расписанию,
   *  которое действовало в тот день (data/derive.ts, scheduleOn). Нет у привычек,
   *  сохранённых на устройстве до истории расписания. */
  schedule_history?: SchedulePeriod[];
  /** Заметки к дням `history` (окно дня в календаре): «ГГГГ-ММ-ДД» → текст. Нет у
   *  привычек, сохранённых на устройстве до заметок. */
  notes?: Record<string, string>;
  /** Совместная привычка (backend/groups.py); null или нет — обычная. В совместной
   *  `history`, серии и `total_done` — по дням, выполненным всеми, а `done_today`,
   *  `today_count` и `history_counts` (при любой цели) — моя часть (её переключает кнопка).
   *  Совместная остаётся совместной, даже когда в ней один человек (isShared). */
  group?: HabitGroup | null;
}

/** Совместная привычка глазами участника. */
export interface HabitGroup {
  id: number;
  /** Я — владелец: меняю общие поля (название, повтор, цель), исключаю участников. */
  is_owner: boolean;
  /** «Отметки участников» включены. */
  notify_marks: boolean;
  /** Активные участники по времени вступления (со мной). */
  members: GroupMember[];
  /** Чёрный список — только у владельца (у остальных пустой): исключённые, по ссылке не
   *  вступят. Нет у групп, сохранённых на устройстве до этого поля. */
  banned?: BannedMember[];
  /** За те же дни, что `history`: выполнили ли свою часть все остальные (дни вне моего
   *  участия — true). День группы = моя отметка и это. */
  others_history: boolean[];
  /** То же за день после дня отметки («Отмечать за вчера»). */
  others_next_day: boolean;
  /** С этого дня день ещё не закончился у кого-то из участников (пояса): невыполненный,
   *  он серию не рвёт. */
  open_from: string | null;
  /** За те же дни, что `history`: сколько раз выполнили остальные, кто был в счёт (каждый —
   *  не больше цели). Нет в ответах, сохранённых до этого поля. */
  others_units?: number[];
  /** За те же дни: сколько человек было в счёт вместе со мной. */
  people?: number[];
  /** За те же дни: доля дня, выполненная всеми (0…1) — ей закрашиваются сетка и календарь
   *  (на устройстве пересчитывается с моими отметками, data/derive.ts). */
  fill_history?: number[];
  /** «Гибкий график»: остальные (бывшие в группе весь мой текущий период) уже набрали в
   *  нём цель — период засчитают, когда наберу я. */
  others_reached?: boolean;
}


export interface GroupMember {
  user_id: number;
  /** @username, если есть, иначе имя из Telegram. */
  name: string;
  is_me: boolean;
  is_owner: boolean;
  /** Выполнил свою часть в день отметки. */
  done: boolean;
  /** Сколько раз выполнил в день отметки (до цели). */
  count: number;
  /** Заморожен в день отметки — не в счёт. */
  frozen: boolean;
  /** «Гибкий график»: сколько дней выполнил в своём текущем периоде. */
  period_done?: number;
  /** Версия фото профиля в Telegram (меняется вместе с фото); null — фото нет, буква.
   *  Нет у групп, сохранённых на устройстве до этого поля. */
  photo?: string | null;
}

/** Исключённый участник в чёрном списке. */
export interface BannedMember {
  user_id: number;
  /** @username, если есть, иначе имя из Telegram. */
  name: string;
  /** Версия фото профиля, как у GroupMember; null — буква. */
  photo?: string | null;
}

/** Прежнее расписание привычки: действовало до дня `until` («ГГГГ-ММ-ДД», не включая его),
 *  с `until` предыдущего периода (первый — с самого начала). */
export interface SchedulePeriod {
  until: string;
  frequency_type: FrequencyType;
  days: string[];
  start_date: string | null;
  period?: Period | null;
  period_times?: number | null;
  times_per_day: number;
  /** «Сверх плана» в дни этого расписания (нет у ответов до него — выключен). */
  overtime?: boolean;
  /** В чём цель этого расписания (нет у ответов до таймера — в разах). */
  goal_unit?: GoalUnit;
}

/** В чём цель привычки: разы или секунды («Цель по времени»). */
export type GoalUnit = "times" | "seconds";

/** Частота выполнения привычки; flexible — «Гибкий график»: N дней за период в любые дни. */
export type FrequencyType = "daily" | "specific_days" | "every_other_day" | "monthly" | "flexible";

/** Период «Гибкого графика». */
export type Period = "week" | "month" | "year";

/** Поля формы привычки: создание и изменение (операции create / update в POST /sync,
 *  как тело POST /tasks и PUT /tasks/{id}). */
export interface HabitInput {
  name: string;
  /** Описание; пустое — без описания. Нет у изменений, сделанных до описаний: тогда
   *  остаётся прежнее. */
  description?: string;
  frequency_type: FrequencyType;
  /** Коды дней недели (mon..sun) для specific_days; для остальных игнорируется. */
  days: string[];
  /** Первый день («ГГГГ-ММ-ДД») для every_other_day и monthly; для остальных — null. */
  start_date: string | null;
  /** «Гибкий график»: период и сколько дней за него (PERIOD_MAX_TIMES); для остальных —
   *  null или нет. */
  period?: Period | null;
  period_times?: number | null;
  /** Первое напоминание «ЧЧ:ММ»; null — без напоминания (его читают старые серверы). */
  reminder_time: string | null;
  /** Все напоминания «ЧЧ:ММ» (до MAX_REMINDERS_PER_HABIT); пустой — без напоминания. Нет
   *  у изменений, сделанных до нескольких напоминаний: тогда одно — `reminder_time`. */
  reminder_times?: string[];
  color: HabitColor;
  /** Сколько раз в день нужно выполнить (1–MAX_TIMES_PER_DAY); у «Цели по времени» —
   *  секунд (MIN_GOAL_SECONDS–MAX_GOAL_SECONDS). */
  times_per_day: number;
  /** «Цель по времени» (seconds) или в разах; у групповой — только в разах. */
  goal_unit?: GoalUnit;
  /** «Автоотметка» (экран привычки); при times_per_day > 1 не действует. */
  auto_mark: boolean;
  /** «Сверх плана»; при times_per_day = 1 не действует. */
  overtime?: boolean;
  /** «Групповая привычка»: true — групповая, false — обычная (выключить можно, только пока
   *  в ней никого, кроме него); нет — при изменении как была. */
  shared?: boolean;
}
